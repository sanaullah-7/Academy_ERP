import { demoWorkflowService } from '../../services/demoWorkflowService.js'
import { beforeEach, describe, expect, it } from 'vitest'
import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '../../App.jsx'
import { authService } from '../../services/authService.js'
import { academicService } from '../../services/academicService.js'
import { MOCK_DATABASE_KEY } from '../../constants/storageKeys.js'

beforeEach(() => history.replaceState(null, '', '/courses-batches'))

async function login(userId, branchId) {
  await authService.login({ userId })
  if (branchId) await authService.selectBranch(userId, branchId)
}

describe('F04 Courses & Batches page', () => {
  it('lets Super Admin search, view, create and edit courses and batches', async () => {
    await login('demo-admin', 'demo-north')
    const user = userEvent.setup()
    render(<App />)
    expect(await screen.findByRole('heading', { name: 'Courses & Batches' })).toBeInTheDocument()
    await screen.findAllByText('Demo Course One')
    await user.type(screen.getByRole('searchbox', { name: 'Search courses' }), 'Demo Course')
    expect(screen.getAllByText('Demo Course One').length).toBeGreaterThan(0)
    await user.clear(screen.getByRole('searchbox'))
    await user.click(screen.getByRole('button', { name: 'Add Course' }))
    await user.type(screen.getByLabelText('Course name'), 'DEMO Robotics')
    await user.click(screen.getByRole('button', { name: 'Add course' }))
    expect(await screen.findByText(/Course “DEMO Robotics” saved/)).toBeInTheDocument()
    await user.click(screen.getByRole('tab', { name: /Batches/ }))
    await user.click(screen.getByRole('button', { name: 'Add Batch' }))
    await user.type(screen.getByLabelText('Batch name'), 'DEMO Robotics Morning')
    await user.selectOptions(screen.getByLabelText('Course'), screen.getByRole('option', { name: 'DEMO Robotics' }))
    await user.click(screen.getByRole('button', { name: 'Add batch' }))
    expect(await screen.findByText(/Batch “DEMO Robotics Morning” saved/)).toBeInTheDocument()
    expect((await screen.findAllByText('DEMO Robotics Morning')).length).toBeGreaterThan(0)
  })
  it('saves Add Stream and Add Subject form submissions to branch storage', async () => {
    await login('demo-admin', 'demo-north')
    const user = userEvent.setup()
    const { unmount } = render(<App />)
    await screen.findByRole('heading', { name: 'Courses & Batches' })
    await user.click(screen.getByRole('button', { name: 'Add Stream' }))
    await user.type(screen.getByLabelText('Academic stream name'), 'DEMO Add Stream')
    await user.click(screen.getByRole('button', { name: 'Save' }))
    expect(await screen.findByText(/Stream “DEMO Add Stream” saved/)).toBeInTheDocument()
    expect(JSON.parse(localStorage.getItem(MOCK_DATABASE_KEY)).academicStreams).toEqual(
      expect.arrayContaining([expect.objectContaining({ name: 'DEMO Add Stream', branchId: 'demo-north' })]),
    )

    await user.click(screen.getByRole('tab',{name:'Subjects',exact:true}))
    await user.click(screen.getByRole('button', { name: 'Add Subject' }))
    await user.type(screen.getByLabelText('Subject name'), 'DEMO Add Subject')
    await user.click(screen.getByRole('button', { name: 'Save' }))
    expect(await screen.findByText(/Subject “DEMO Add Subject” saved/)).toBeInTheDocument()
    expect(JSON.parse(localStorage.getItem(MOCK_DATABASE_KEY)).subjects).toEqual(
      expect.arrayContaining([expect.objectContaining({ name: 'DEMO Add Subject', branchId: 'demo-north' })]),
    )

    unmount()
    render(<App />)
    expect((await screen.findAllByText('DEMO Add Stream')).length).toBeGreaterThan(0)
    await user.click(screen.getByRole('tab',{name:'Subjects',exact:true}))
    expect(await screen.findByText('DEMO Add Subject')).toBeInTheDocument()
    expect(screen.getAllByText('Demo Course One').length).toBeGreaterThan(0)
  })
  it('shows the saved stream, course, subject and batch relationships clearly', async () => {
    await login('demo-admin', 'demo-north')
    await demoWorkflowService.setup({branchId:'demo-north'})
    render(<App />)
    expect(screen.queryByRole('button',{name:'Set Up QA Demo'})).not.toBeInTheDocument()
    expect(await screen.findByText('Academic Portfolios')).toBeInTheDocument()
    const portfolio = (await screen.findAllByText('QA Pre-Medical')).map(item => item.closest('article')).find(Boolean)
    expect(within(portfolio).getByText('QA MDCAT Preparation')).toBeInTheDocument()
    expect(within(portfolio).getByText('Courses')).toBeInTheDocument()
    expect(within(portfolio).getByText('Subjects')).toBeInTheDocument()
    expect(within(portfolio).getByText('Batches')).toBeInTheDocument()
    expect(screen.queryByText('QA Biology')).not.toBeInTheDocument()
    await userEvent.setup().click(screen.getByRole('tab',{name:'Subjects',exact:true}))
    const subjectRow = screen.getByText('QA Biology').closest('tr')
    expect(within(subjectRow).getByText('QA MDCAT Preparation')).toBeInTheDocument()
    expect(within(subjectRow).getByText('QA Pre-Medical')).toBeInTheDocument()
    expect(screen.getAllByRole('columnheader', { name: 'Academic stream' })).toHaveLength(1)
    await userEvent.setup().click(screen.getByRole('tab',{name:'Courses',exact:true}))
    expect(screen.getAllByText(/subjects · .*batches/).length).toBeGreaterThan(0)
  })
  it('paginates the subjects table with configurable rows per page', async () => {
    await login('demo-admin', 'demo-north')
    for (let index = 1; index <= 6; index += 1) await academicService.saveSubject(null, { name: `Paged Subject ${index}`, courseId: 'course-demo-1', active: true }, { branchId: 'demo-north' })
    const user = userEvent.setup()
    render(<App />)
    await user.click(await screen.findByRole('tab',{name:'Subjects',exact:true}))
    expect(await screen.findByText('Paged Subject 1')).toBeInTheDocument()
    expect(screen.getByLabelText('Subjects rows per page')).toHaveValue('10')
    expect(screen.getByText('Paged Subject 6')).toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Subjects rows per page'), '5')
    expect(screen.queryByText('Paged Subject 6')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Subjects page 2' }))
    expect(await screen.findByText('Paged Subject 6')).toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Subjects rows per page'), '10')
    expect(await screen.findByText('Paged Subject 1')).toBeInTheDocument()
    expect(screen.getByText('1–6 of 6')).toBeInTheDocument()
  })
  it('uses the three-dot menu to view, edit and safely delete unlinked records', async () => {
    await login('demo-admin', 'demo-north')
    const user = userEvent.setup()
    render(<App />)
    await screen.findByRole('heading', { name: 'Courses & Batches' })
    await user.click(screen.getByRole('button', { name: 'Add Course' }))
    await user.type(screen.getByLabelText('Course name'), 'DEMO Disposable Course')
    await user.click(screen.getByRole('button', { name: 'Add course' }))
    const row = () => screen.getAllByRole('row').find(item => within(item).queryByText('DEMO Disposable Course'))
    await user.click(within(row()).getByLabelText('Actions for DEMO Disposable Course'))
    expect(within(row()).getByRole('menuitem', { name: 'View' })).toBeInTheDocument()
    expect(within(row()).getByRole('menuitem', { name: 'Edit' })).toBeInTheDocument()
    await user.click(screen.getByRole('heading', { name: 'Courses & Batches' }))
    expect(within(row()).queryByRole('menu')).not.toBeInTheDocument()
    await user.click(within(row()).getByLabelText('Actions for DEMO Disposable Course'))
    await user.click(within(row()).getByRole('menuitem', { name: 'Delete' }))
    await user.click(screen.getByRole('button', { name: 'Delete permanently' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Course “DEMO Disposable Course” deleted.')
    expect(screen.queryByText('DEMO Disposable Course')).not.toBeInTheDocument()
  })
  it('clears stale delete errors and labels Batch deletion correctly', async () => {
    await login('demo-admin', 'demo-north')
    const user = userEvent.setup()
    render(<App />)
    await screen.findByRole('heading', { name: 'Courses & Batches' })
    await screen.findAllByText('Demo Course One')
    const courseRow = screen.getAllByRole('row').find(item => within(item).queryByText('Demo Course One'))
    await user.click(within(courseRow).getByLabelText('Actions for Demo Course One'))
    await user.click(within(courseRow).getByRole('menuitem', { name: 'Delete' }))
    await user.click(screen.getByRole('button', { name: 'Delete permanently' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Delete linked batches')
    await user.click(screen.getByRole('button', { name: 'Cancel' }))
    await user.click(screen.getByRole('tab', { name: /Batches/ }))
    const batchRow = screen.getAllByRole('row').find(item => within(item).queryByText('DEMO Batch - Demo Course One'))
    await user.click(within(batchRow).getByLabelText('Actions for DEMO Batch - Demo Course One'))
    await user.click(within(batchRow).getByRole('menuitem', { name: 'Delete' }))
    expect(screen.getByRole('dialog', { name: 'Delete Batch' })).toBeInTheDocument()
    expect(screen.queryByText('Delete linked batches, subjects and student records before deleting this course.')).not.toBeInTheDocument()
  })
  it('offers working three-dot deletion for unlinked streams and subjects', async () => {
    await login('demo-admin', 'demo-north')
    const user = userEvent.setup()
    render(<App />)
    await screen.findByRole('heading', { name: 'Courses & Batches' })
    await user.click(screen.getByRole('button', { name: 'Add Stream' }))
    await user.type(screen.getByLabelText('Academic stream name'), 'Disposable Stream UI')
    await user.click(screen.getByRole('button', { name: 'Save' }))
    await user.click(screen.getByLabelText('Actions for Disposable Stream UI'))
    await user.click(screen.getByRole('menuitem', { name: 'Delete' }))
    await user.click(screen.getByRole('button', { name: 'Delete permanently' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Academic stream “Disposable Stream UI” deleted.')
    await user.click(screen.getByRole('tab',{name:'Subjects',exact:true}))
    await user.click(screen.getByRole('button', { name: 'Add Subject' }))
    await user.type(screen.getByLabelText('Subject name'), 'Disposable Subject UI')
    await user.click(screen.getByRole('button', { name: 'Save' }))
    await user.click(screen.getByLabelText('Actions for Disposable Subject UI'))
    await user.click(screen.getByRole('menuitem', { name: 'Delete' }))
    await user.click(screen.getByRole('button', { name: 'Delete permanently' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Subject “Disposable Subject UI” deleted.')
  })
  it.each([['demo-reception', 'demo-north'], ['demo-owner', null]])('%s gets the read-only directory', async (userId, branchId) => {
    await login(userId, branchId)
    render(<App />)
    expect(await screen.findByRole('heading', { name: 'Courses & Batches' })).toBeInTheDocument()
    await screen.findAllByText(userId === 'demo-reception' ? 'Demo Course One' : 'Demo Course Two')
    expect(screen.queryByRole('button', { name: 'Add Course' })).not.toBeInTheDocument()
    const row = screen.getAllByRole('row').find(item => within(item).queryByText(userId === 'demo-reception' ? 'Demo Course One' : 'Demo Course Two'))
    await userEvent.setup().click(within(row).getByLabelText(`Actions for ${userId === 'demo-reception' ? 'Demo Course One' : 'Demo Course Two'}`))
    expect(within(row).getByRole('menuitem', { name: 'View' })).toBeInTheDocument()
    expect(within(row).queryByRole('menuitem', { name: 'Edit' })).not.toBeInTheDocument()
    expect(within(row).queryByRole('menuitem', { name: 'Delete' })).not.toBeInTheDocument()
  })
  it('denies Teacher because assignment-based access is unresolved', async () => {
    await login('demo-teacher')
    render(<App />)
    expect(await screen.findByRole('heading', { name: 'Access unavailable' })).toBeInTheDocument()
  })
})
